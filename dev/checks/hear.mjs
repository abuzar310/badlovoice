import pw from 'playwright'; const { chromium, devices } = pw;
const S = process.argv[2];
const browser = await chromium.launch({ args: ['--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream', `--use-file-for-fake-audio-capture=${S}/mic.wav`] });
const ctx = await browser.newContext({ ...devices['Pixel 7'], permissions: ['microphone'] });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.goto('http://127.0.0.1:5173/');
await page.waitForTimeout(800);
await page.getByRole('button', { name: /Start voice/ }).click();
await page.waitForTimeout(1500);
const notice = page.getByText('You are live, but the speakers are muted');
console.log('notice visible when live + muted:', await notice.isVisible());
await page.screenshot({ path: `${S}/hear-phone.png` });
await page.getByRole('button', { name: 'Hear myself', exact: true }).click();
await page.waitForTimeout(400);
console.log('after tapping Hear myself → notice visible:', await notice.isVisible(), '| checkbox checked:', await page.getByRole('checkbox', { name: /Hear myself/ }).isChecked(), '| stored:', await page.evaluate(() => localStorage.getItem('badlovoice_hear_myself')));
console.log('mic options locked while live:', await page.locator('fieldset:has-text("Mic clean-up") input').count() ? await page.locator('fieldset:has-text("Mic clean-up") input').first().isDisabled() : 'panel hidden in this density');
console.log('errors:', errors.length ? errors : 'none');
await browser.close();
