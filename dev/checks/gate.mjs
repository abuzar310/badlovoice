import pw from 'playwright'; const { chromium } = pw;
const S = process.argv[2];
const browser = await chromium.launch({ args: ['--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream', `--use-file-for-fake-audio-capture=${S}/mic.wav`] });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, permissions: ['microphone'] });
const page = await ctx.newPage();
const errors = []; page.on('pageerror', (e) => errors.push(e.message));
await page.goto('http://127.0.0.1:5173/');
await page.waitForTimeout(1500);
await page.getByRole('button', { name: /Advanced effects/ }).click();
await page.waitForTimeout(300);
const card = page.locator('div:has(> div > div > p:text-is("Noise Gate"))').first();
const sw = page.getByRole('switch').first();
console.log('rack gate switch before:', await sw.getAttribute('aria-checked'));
await sw.click(); await page.waitForTimeout(300);
console.log('after click:', await sw.getAttribute('aria-checked'), '| extras:', await page.evaluate(() => localStorage.getItem('shiftbooth_extras_v10')));
await sw.click(); await page.waitForTimeout(300);
console.log('after 2nd click:', await sw.getAttribute('aria-checked'));
await page.getByRole('button', { name: 'Models', exact: true }).click(); await page.waitForTimeout(500);
console.log('models tiles shown offline:', await page.getByText('Sample rate', { exact: true }).count());
console.log('errors:', errors.length ? errors : 'none');
await browser.close();
